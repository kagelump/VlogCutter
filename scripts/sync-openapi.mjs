import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const result = spawnSync(
  "cargo",
  ["run", "--quiet", "-p", "rcdvlog-server", "--", "--openapi-json"],
  { cwd: root, encoding: "utf8" },
);
if (result.status !== 0) {
  process.stderr.write(result.stderr);
  process.exit(result.status ?? 1);
}

const parsed = JSON.parse(result.stdout);
const schema = `${JSON.stringify(parsed, null, 2)}\n`;
const digest = createHash("sha256").update(schema).digest("hex");
const generated = `// Generated by scripts/sync-openapi.mjs. Do not edit by hand.
export const OPENAPI_SCHEMA_SHA256 = "${digest}";
export const API_PATHS = {
  version: "/api/v1/version",
  ready: "/api/v1/ready",
  sessions: "/api/v1/auth/sessions",
  bootstrapExchange: "/api/v1/auth/bootstrap/exchange",
  libraryMedia: "/api/v1/library/media",
  projects: "/api/v1/projects",
  projectAssets: "/api/v1/projects/{projectId}/assets",
  previewAddToProject: "/api/v1/projects/{projectId}/assets/add/preview",
  addToProject: "/api/v1/projects/{projectId}/assets/add",
  projectReviewAsset: "/api/v1/projects/{projectId}/assets/{assetId}/review",
  createReviewNote: "/api/v1/projects/{projectId}/assets/{assetId}/notes",
  addReviewLabel: "/api/v1/projects/{projectId}/assets/{assetId}/labels/add",
  removeReviewLabel: "/api/v1/projects/{projectId}/assets/{assetId}/labels/remove",
  setReviewRemoved: "/api/v1/projects/{projectId}/assets/{assetId}/removed",
  setReviewRotation: "/api/v1/projects/{projectId}/assets/{assetId}/rotation",
  devices: "/api/v1/auth/devices",
  revokeDevice: "/api/v1/auth/devices/{credentialId}",
  revokeSession: "/api/v1/auth/sessions/{sessionId}",
  adminOverview: "/api/v1/admin/overview",
  adminAudit: "/api/v1/admin/audit",
  adminStorageRoots: "/api/v1/admin/storage-roots",
  adminStorageRoot: "/api/v1/admin/storage-roots/{rootId}",
  adminStorageBindings: "/api/v1/admin/storage-bindings",
  adminStorageBinding: "/api/v1/admin/storage-roots/{rootId}/binding",
  adminStorageBindingConfirmation: "/api/v1/admin/storage-roots/{rootId}/binding/confirmation",
  adminStorageBindingVerification: "/api/v1/admin/storage-roots/{rootId}/binding/verify",
  adminScans: "/api/v1/admin/scans",
  adminScanDiagnostics: "/api/v1/admin/scans/{scanId}/diagnostics",
  adminScanSchedules: "/api/v1/admin/scan-schedules",
  adminScanSchedule: "/api/v1/admin/scan-schedules/{scheduleId}",
  adminJobs: "/api/v1/admin/jobs",
  adminJob: "/api/v1/admin/jobs/{jobId}",
  adminJobCancel: "/api/v1/admin/jobs/{jobId}/cancel",
  adminJobRetry: "/api/v1/admin/jobs/{jobId}/retry",
  adminJobCallbacks: "/api/v1/admin/jobs/{jobId}/callbacks",
  adminJobCallbackDeliveries: "/api/v1/admin/job-callbacks",
  adminJobCallbackClaim: "/api/v1/admin/job-callbacks/claim",
  adminJobCallbackSettle: "/api/v1/admin/job-callbacks/{deliveryId}/settle",
  adminSync: "/api/v1/admin/sync",
  adminRepresentationBatch: "/api/v1/admin/representations/batch",
} as const;
`;
const schemaPath = resolve(root, "packages/project-client/openapi.json");
const clientPath = resolve(root, "packages/project-client/src/generated.ts");

if (process.argv.includes("--check")) {
  const matches = readFileSync(schemaPath, "utf8") === schema
    && readFileSync(clientPath, "utf8") === generated;
  if (!matches) {
    console.error("OpenAPI artifacts are stale. Run `pnpm generate:openapi`.");
    process.exit(1);
  }
} else {
  writeFileSync(schemaPath, schema);
  writeFileSync(clientPath, generated);
}
